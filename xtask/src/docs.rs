//! `cargo xtask docs`: regenerate the generated parts of the guide.
//!
//! - Sections between `<!-- generated:start NAME -->` and `<!-- generated:end -->`
//!   in `README.md` and `docs/guide/*.md` (see [`generate`] for the names).
//! - `docs/guide/llms.txt` (an index of the pages) and `docs/guide/llms-full.txt`
//!   (every page in one file), for language models. mdBook copies both to the site.
//!
//! The pages are the source; edit them, then run this task. `cargo xtask check`
//! fails when the committed files differ from what this task writes.
//!
//! Examples run the real binary against the small database in
//! `fixtures/smoke/` with a fixed date, so the output is the same on every run.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::OnceLock;

use anyhow::{Context, Result, bail};
use serde_json::Value;

const START: &str = "<!-- generated:start ";
const END: &str = "<!-- generated:end -->";
const SITE: &str = "https://amet13.github.io/unpatched/";

/// The clock for every example, so the output never changes with the date.
const NOW: &str = "2026-11-24T00:00:00Z";
const SMOKE_DB: &str = "fixtures/smoke/unpatched-db.sqlite";
const TEMPLATE_DIR: &str = "templates/github";

fn root() -> PathBuf {
    crate::repo_root()
}

fn read(rel: &str) -> Result<String> {
    let path = root().join(rel);
    fs::read_to_string(&path).with_context(|| format!("cannot read {}", path.display()))
}

// ---------------------------------------------------------------- the task

/// Every file this task owns, with the content it should have.
fn outputs() -> Result<Vec<(PathBuf, String)>> {
    let guide = root().join("docs/guide");
    let mut files = vec![root().join("README.md")];
    let mut pages = Vec::new();
    for entry in fs::read_dir(&guide).with_context(|| format!("cannot read {}", guide.display()))? {
        let p = entry?.path();
        if p.extension().is_some_and(|e| e == "md") {
            pages.push(p);
        }
    }
    pages.sort();
    files.extend(pages);

    let mut out = Vec::new();
    for path in files {
        let text =
            fs::read_to_string(&path).with_context(|| format!("cannot read {}", path.display()))?;
        let new = fill(&text).with_context(|| format!("in {}", path.display()))?;
        out.push((path, new));
    }

    let order = summary_pages(&read("docs/guide/SUMMARY.md")?);
    let mut index = String::new();
    let mut full = String::new();
    let _ = writeln!(
        index,
        "# unpatched\n\n> unpatched tells you when software you run (a firewall, a NAS, self-hosted apps, databases) is affected by a vulnerability: which version to upgrade to, and whether it is being exploited. It checks a list of what you run (`unpatched.yml`) against open data every day, in a GitHub Action, and opens an issue only when something needs action. It needs no account or API key.\n\nIt is not a scanner for code dependencies or container images; use OSV-Scanner or Trivy for that.\n\n## Guide\n"
    );
    let _ = writeln!(
        full,
        "# unpatched: the full guide\n\nThis file is every page of the guide ({SITE}) in one text. Generated by `cargo xtask docs`.\n"
    );
    for (title, file) in &order {
        let (_, text) = out
            .iter()
            .find(|(p, _)| p.file_name().is_some_and(|n| n == file.as_str()))
            .with_context(|| format!("SUMMARY.md lists {file}, which does not exist"))?;
        let url = format!("{SITE}{}", file.replace(".md", ".html"));
        let desc = description(text)
            .with_context(|| format!("{file} has no `<!-- description: ... -->` line"))?;
        let _ = writeln!(index, "- [{title}]({url}): {desc}");
        let _ = write!(
            full,
            "\n---\n\nSource: {url}\n\n{}\n",
            strip_description(text).trim()
        );
    }
    let _ = writeln!(
        index,
        "\n## More\n\n- [Everything in one file]({SITE}llms-full.txt)\n- [Source code](https://github.com/Amet13/unpatched)\n- [Config schema](https://github.com/Amet13/unpatched/blob/main/schema/unpatched.schema.json)\n- [Report schema](https://github.com/Amet13/unpatched/blob/main/schema/report.schema.json)"
    );
    out.push((guide.join("llms.txt"), index));
    out.push((guide.join("llms-full.txt"), full));
    Ok(out)
}

pub fn build() -> Result<()> {
    for (path, content) in outputs()? {
        if fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
            fs::write(&path, content)
                .with_context(|| format!("cannot write {}", path.display()))?;
            eprintln!("wrote {}", rel(&path));
        }
    }
    Ok(())
}

pub fn check() -> Result<()> {
    let mut stale = Vec::new();
    for (path, content) in outputs()? {
        if fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
            stale.push(rel(&path));
        }
    }
    if stale.is_empty() {
        eprintln!("docs: generated sections are up to date");
        Ok(())
    } else {
        bail!(
            "generated docs are out of date: {}. Run `cargo xtask docs` and commit the result.",
            stale.join(", ")
        )
    }
}

fn rel(p: &Path) -> String {
    p.strip_prefix(root()).unwrap_or(p).display().to_string()
}

// ---------------------------------------------------------------- pages

/// `(title, file)` for every `- [Title](file.md)` line of `SUMMARY.md`.
fn summary_pages(summary: &str) -> Vec<(String, String)> {
    summary
        .lines()
        .filter_map(|l| {
            let l = l.trim().strip_prefix("- [")?;
            let (title, rest) = l.split_once("](")?;
            let file = rest.strip_suffix(')')?;
            Path::new(file)
                .extension()
                .is_some_and(|e| e == "md")
                .then(|| (title.to_owned(), file.to_owned()))
        })
        .collect()
}

fn description(text: &str) -> Option<String> {
    text.lines().find_map(|l| {
        let l = l.trim().strip_prefix("<!-- description:")?;
        Some(l.strip_suffix("-->")?.trim().to_owned())
    })
}

fn strip_description(text: &str) -> String {
    let mut out: Vec<&str> = text
        .lines()
        .filter(|l| !l.trim().starts_with("<!-- description:"))
        .collect();
    // The two comment lines around a generated block add nothing for a reader of the text.
    out.retain(|l| !l.trim().starts_with(START) && l.trim() != END);
    let mut s = out.join("\n");
    s.push('\n');
    s
}

/// Replace the body of every generated block.
fn fill(text: &str) -> Result<String> {
    let mut out = String::new();
    let mut lines = text.lines();
    while let Some(line) = lines.next() {
        out.push_str(line);
        out.push('\n');
        let Some(name) = line
            .trim()
            .strip_prefix(START)
            .and_then(|r| r.strip_suffix("-->"))
            .map(str::trim)
        else {
            continue;
        };
        let mut closed = false;
        for inner in lines.by_ref() {
            if inner.trim() == END {
                closed = true;
                break;
            }
        }
        if !closed {
            bail!("generated block {name:?} has no `{END}`");
        }
        let body = generate(name).with_context(|| format!("generating {name:?}"))?;
        out.push('\n');
        out.push_str(body.trim_end());
        out.push_str("\n\n");
        out.push_str(END);
        out.push('\n');
    }
    Ok(out)
}

// ---------------------------------------------------------------- generators

/// The Markdown for one generated block.
fn generate(name: &str) -> Result<String> {
    match name {
        "config-reference" => config_reference(),
        "rules" => rules(),
        "catalog-table" => Ok(catalog_table()),
        "cli-help" => cli_help(),
        "action-inputs" => action_inputs(),
        "template-config" => Ok(fenced(
            "yaml",
            &read(&format!("{TEMPLATE_DIR}/unpatched.yml"))?,
        )),
        "template-workflow" => Ok(fenced(
            "yaml",
            &read(&format!("{TEMPLATE_DIR}/workflow.yml"))?,
        )),
        "example-issue" => example_issue(),
        "example-digest" => example_snapshot("message__tests__digest_plain"),
        "example-alert" => example_snapshot("message__tests__alert_plain"),
        "example-check" => example(
            "unpatched check",
            &["check", "--now", NOW, "--config", &template_config()],
            None,
        ),
        "example-check-markdown" => example(
            "unpatched check --format markdown",
            &[
                "check",
                "--format",
                "markdown",
                "--now",
                NOW,
                "--config",
                &template_config(),
            ],
            None,
        ),
        "example-check-json" => example_check_json(),
        "example-explain-rule" => {
            example("unpatched explain UNP-KEV", &["explain", "UNP-KEV"], None)
        }
        "example-explain-cve" => example(
            "unpatched explain CVE-2024-21762",
            &["explain", "CVE-2024-21762", "--config", "no-such-file.yml"],
            Some(9),
        ),
        "example-search" => example("unpatched search forti", &["search", "forti"], None),
        "example-catalog-show" => example(
            "unpatched catalog show fortios",
            &["catalog", "show", "fortios"],
            None,
        ),
        "example-db-info" => example_db_info(),
        "example-init" => example_init(),
        other => {
            bail!("unknown generated block {other:?}; add it to `generate` in xtask/src/docs.rs")
        }
    }
}

fn fenced(lang: &str, text: &str) -> String {
    // A fence longer than any run of backticks in the text, so a code block
    // inside the example (an issue body with a YAML snippet) cannot close it.
    let longest = text
        .split(|c| c != '`')
        .map(str::len)
        .max()
        .unwrap_or(0);
    let fence = "`".repeat(longest.max(2) + 1);
    format!("{fence}{lang}\n{}\n{fence}", text.trim_end())
}

fn template_config() -> String {
    format!("{TEMPLATE_DIR}/unpatched.yml")
}

// ---- running the binary

fn binary() -> Result<&'static Path> {
    static BIN: OnceLock<PathBuf> = OnceLock::new();
    if let Some(b) = BIN.get() {
        return Ok(b);
    }
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let status = Command::new(cargo)
        .args(["build", "--quiet", "-p", "unpatched"])
        .current_dir(root())
        .status()
        .context("could not start cargo")?;
    if !status.success() {
        bail!("`cargo build -p unpatched` failed");
    }
    let target =
        std::env::var_os("CARGO_TARGET_DIR").map_or_else(|| root().join("target"), PathBuf::from);
    let name = if cfg!(windows) {
        "unpatched.exe"
    } else {
        "unpatched"
    };
    Ok(BIN.get_or_init(|| target.join("debug").join(name)))
}

/// Run `unpatched <args>` against the smoke database; returns stdout and stderr
/// (in that order) and the exit code.
fn run_in(dir: &Path, args: &[&str], with_db: bool) -> Result<String> {
    let mut cmd = Command::new(binary()?);
    cmd.current_dir(dir)
        .args(args)
        .args(["--offline", "--color", "never"])
        .env("NO_COLOR", "1")
        .env_remove("UNPATCHED_DB")
        .env_remove("UNPATCHED_CACHE_DIR")
        .env_remove("GITHUB_ACTIONS")
        .env_remove("GITHUB_STEP_SUMMARY")
        .env_remove("GITHUB_TOKEN")
        .stdin(Stdio::null());
    if with_db {
        cmd.arg("--db").arg(root().join(SMOKE_DB));
    }
    let out = cmd.output().context("could not run unpatched")?;
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    Ok(text)
}

fn run(args: &[&str]) -> Result<String> {
    run_in(&root(), args, true)
}

/// A command and its output as a `text` block. `max_lines` cuts long output and says so.
fn example(shown: &str, args: &[&str], max_lines: Option<usize>) -> Result<String> {
    let out = run(args)?;
    Ok(console(shown, &out, max_lines))
}

fn console(shown: &str, out: &str, max_lines: Option<usize>) -> String {
    let mut lines: Vec<&str> = out.trim_end().lines().collect();
    let mut cut = false;
    if let Some(n) = max_lines
        && lines.len() > n
    {
        lines.truncate(n);
        cut = true;
    }
    let mut s = format!("```text\n$ {shown}\n");
    for l in lines {
        s.push_str(l.trim_end());
        s.push('\n');
    }
    if cut {
        s.push_str("...\n");
    }
    s.push_str("```");
    s
}

fn example_db_info() -> Result<String> {
    let out = run(&["db", "info"])?;
    // `db info` counts the age from the real clock; the sample database was built on
    // 2026-11-23, so the examples use the age on the sample date.
    let re = regex::Regex::new(r"\(\d+ days? old\)").expect("a valid pattern");
    let out = re.replace_all(&out, "(0 days old)");
    // The file path is the caller's; show the plain command.
    let out = out.replace(&root().join(SMOKE_DB).display().to_string(), SMOKE_DB);
    Ok(console("unpatched db info", &out, None))
}

fn example_init() -> Result<String> {
    let dir = tempfile::tempdir().context("no temporary folder")?;
    let out = run_in(dir.path(), &["init", "--github"], false)?;
    Ok(console("unpatched init --github", &out, None))
}

/// `check --format json`, with the database sources, the long `title` and
/// `evidence` fields and every finding after the first cut out (marked `...`).
/// Cut as text, so the keys stay in the order the program writes them.
fn example_check_json() -> Result<String> {
    let out = run(&[
        "check",
        "--format",
        "json",
        "--now",
        NOW,
        "--config",
        &template_config(),
    ])?;
    serde_json::from_str::<Value>(&out).context("check --format json is not JSON")?;
    let mut shown: Vec<String> = Vec::new();
    // What to skip until: the line that closes the block that was cut.
    let mut skip_until: Option<String> = None;
    let mut findings_seen = 0;
    for line in out.trim_end().lines() {
        if let Some(close) = &skip_until {
            if line.trim_end_matches(',') == close.trim_end_matches(',') {
                skip_until = None;
            }
            continue;
        }
        let indent = line.len() - line.trim_start().len();
        let pad = " ".repeat(indent);
        let t = line.trim_start();
        if indent == 2 && t.starts_with("\"db\": {") {
            shown.push(format!("{pad}\"db\": {{ ... }},"));
            skip_until = Some(format!("{pad}}},"));
        } else if indent == 4 && t == "{" {
            findings_seen += 1;
            if findings_seen == 1 {
                shown.push(line.to_owned());
            } else {
                shown.push(format!("{pad}..."));
                skip_until = Some(format!("{pad}}}"));
            }
        } else if indent == 6 && t.starts_with("\"title\":") {
            shown.push(format!("{pad}\"title\": \"...\","));
        } else if indent == 6 && t.starts_with("\"evidence\": [") {
            shown.push(format!("{pad}\"evidence\": [ ... ],"));
            skip_until = Some(format!("{pad}],"));
        } else {
            shown.push(line.to_owned());
        }
    }
    Ok(format!("```json\n{}\n```", shown.join("\n")))
}

// ---- the issue and message examples come from the renderer's own snapshots

fn snapshot_body(name: &str) -> Result<String> {
    let text = read(&format!(
        "crates/unpatched-notify/src/snapshots/unpatched_notify__{name}.snap"
    ))?;
    // A snapshot starts with a front matter block between two `---` lines.
    let mut parts = text.splitn(3, "---\n");
    parts.next();
    parts.next();
    Ok(parts
        .next()
        .context("a snapshot without a body")?
        .trim()
        .to_owned())
}

